"""
Boundary condition operators.

Each function modifies the supplied tensors in-place and returns them
for convenience.
"""

import torch


# ============================================================
# Velocity BCs
# ============================================================

def apply_cavity_velocity_bc(
    u,
    v,
    w,
    lid_velocity=1.0,
):
    """
    3D Lid-driven cavity boundary conditions.

    Domain:
        x ∈ [0,1]
        y ∈ [0,1]
        z ∈ [0,1]

    Moving lid:
        y = 1

    Remaining walls:
        No-slip
    """

    # --------------------------------------------------------
    # Bottom wall
    # --------------------------------------------------------

    u[:, 0, :] = 0.0
    v[:, 0, :] = 0.0
    w[:, 0, :] = 0.0

    # --------------------------------------------------------
    # Top lid
    # --------------------------------------------------------

    u[:, -1, :] = lid_velocity
    v[:, -1, :] = 0.0
    w[:, -1, :] = 0.0

    # --------------------------------------------------------
    # Left wall
    # --------------------------------------------------------

    u[0, :, :] = 0.0
    v[0, :, :] = 0.0
    w[0, :, :] = 0.0

    # --------------------------------------------------------
    # Right wall
    # --------------------------------------------------------

    u[-1, :, :] = 0.0
    v[-1, :, :] = 0.0
    w[-1, :, :] = 0.0

    # --------------------------------------------------------
    # Front wall
    # --------------------------------------------------------

    u[:, :, 0] = 0.0
    v[:, :, 0] = 0.0
    w[:, :, 0] = 0.0

    # --------------------------------------------------------
    # Back wall
    # --------------------------------------------------------

    u[:, :, -1] = 0.0
    v[:, :, -1] = 0.0
    w[:, :, -1] = 0.0

    return u, v, w


# ============================================================
# Pressure BCs
# ============================================================

def apply_pressure_bc(
    p,
):
    """
    Pressure boundary conditions.

    Neumann BC:
        ∂p/∂n = 0

    Pressure is fixed at one point to remove the
    arbitrary constant.
    """

    # x-direction

    p[0, :, :] = p[1, :, :]
    p[-1, :, :] = p[-2, :, :]

    # y-direction

    p[:, 0, :] = p[:, 1, :]
    p[:, -1, :] = p[:, -2, :]

    # z-direction

    p[:, :, 0] = p[:, :, 1]
    p[:, :, -1] = p[:, :, -2]

    # Reference pressure

    p[0, 0, 0] = 0.0

    return p
